import path from 'path'

const glob = new Bun.Glob('**/*.ts')

const commandsDir = 'src/commands'

const commands: { name: string; path: string }[] = []

console.log('Generating commands import... \nType checking has not yet been implemented.')

for await (const filePath of glob.scan(commandsDir)) {
  const name = path.basename(filePath, '.ts')
  const filePathStr = filePath.replace(/\\/g, '/')

  if (name === 'index') continue

  commands.push({ name, path: filePathStr })
}

const output = Bun.file(commandsDir + '/index.ts')

await output.write(
  `// Generated by generate-commands-index.ts
// Type checking has not yet been implemented.

import { Collection } from 'discord.js'
import type { Command } from '@/types/discord.ts'

${commands.map((cmd) => `import ${cmd.name} from './${cmd.path}'`).join('\n')}

const commands = new Collection<string, Command>()

${commands.map((cmd) => `commands.set('${cmd.name}', ${cmd.name})`).join('\n')}

export default commands
`
)

console.log('Generated commands imports in', commandsDir + '/index.ts')
